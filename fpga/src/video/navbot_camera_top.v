`timescale 1ns/1ps
// Camera uses the supplied MIPI/DDR3/HDMI pipeline; the controller stays at 50 MHz.
// OLED is removed in this integration to make room for the video pipeline.
module navbot_camera_top(
    input wire clk,
    input wire [2:0] key_n,
    input wire [3:0] encoder_a,encoder_b,
    output wire [3:0] motor_in1,motor_in2,motor_pwm,
    output wire [1:0] servo_pwm,
    input wire vision_rx,tof_rx,
    inout wire imu_sda,
    output wire vision_tx,tof_tx,imu_scl,
    input wire debug_rx,
    output wire debug_tx,
    input wire nav_rx,
    output wire nav_tx,
    inout       ck_n,
    inout       ck_p,
    inout       d0_n,
    inout       d0_p,
    inout       d1_n,
    inout       d1_p,
    output      O_CSI_SCL,
    inout       IO_CSI_SDA,
    output      camera_pwdn,
    output	   [13:0] O_ddr_addr,
    output	   [2:0]  O_ddr_ba,
    output 	   	      O_ddr_cs_n,
    output 	   	      O_ddr_ras_n,
    output 	   	      O_ddr_cas_n,
    output 	   	      O_ddr_we_n,
    output 	   	      O_ddr_clk,
    output 	   	      O_ddr_clk_n,
    output 	   	      O_ddr_cke,
    output 	   	      O_ddr_odt,
    output 	   	      O_ddr_reset_n,
    output 	   [1:0]  O_ddr_dqm,
    inout  	   [15:0] IO_ddr_dq,
    inout  	   [1:0]  IO_ddr_dqs,
    inout  	   [1:0]  IO_ddr_dqs_n,
    output	   		  O_tmds_clk_p,
    output	   		  O_tmds_clk_n,
    output	   [2:0]  O_tmds_data_p,
    output	   [2:0]  O_tmds_data_n,
    output [1:0]      led
);
    wire signed [15:0] yaw_cdeg;
    wire yaw_fresh,reset_n;
    wire unused_scl,unused_sda;
    navbot_controller #(.OLED_ENABLE(0),.SHARED_PI(1)) controller(
        .clk(clk),.key_n(key_n),.encoder_a(encoder_a),.encoder_b(encoder_b),
        .motor_in1(motor_in1),.motor_in2(motor_in2),.motor_pwm(motor_pwm),.servo_pwm(servo_pwm),
        .vision_rx(vision_rx),.tof_rx(tof_rx),.imu_sda(imu_sda),
        .vision_tx(vision_tx),.tof_tx(tof_tx),.imu_scl(imu_scl),
        .oled_scl(unused_scl),.oled_sda(unused_sda),.debug_rx(debug_rx),.debug_tx(debug_tx),
        .nav_rx(nav_rx),.nav_tx(nav_tx),
        .video_yaw_cdeg(yaw_cdeg),.video_yaw_fresh(yaw_fresh),.video_reset_n(reset_n));
    mipi_ov5647_hdmi camera(
        .clk_50M(clk),.Rst_n(reset_n),.yaw_cdeg(yaw_cdeg),.yaw_fresh(yaw_fresh),
        .ck_n(ck_n),
        .ck_p(ck_p),
        .d0_n(d0_n),
        .d0_p(d0_p),
        .d1_n(d1_n),
        .d1_p(d1_p),
        .O_CSI_SCL(O_CSI_SCL),
        .IO_CSI_SDA(IO_CSI_SDA),
        .camera_pwdn(camera_pwdn),
        .O_ddr_addr(O_ddr_addr),
        .O_ddr_ba(O_ddr_ba),
        .O_ddr_cs_n(O_ddr_cs_n),
        .O_ddr_ras_n(O_ddr_ras_n),
        .O_ddr_cas_n(O_ddr_cas_n),
        .O_ddr_we_n(O_ddr_we_n),
        .O_ddr_clk(O_ddr_clk),
        .O_ddr_clk_n(O_ddr_clk_n),
        .O_ddr_cke(O_ddr_cke),
        .O_ddr_odt(O_ddr_odt),
        .O_ddr_reset_n(O_ddr_reset_n),
        .O_ddr_dqm(O_ddr_dqm),
        .IO_ddr_dq(IO_ddr_dq),
        .IO_ddr_dqs(IO_ddr_dqs),
        .IO_ddr_dqs_n(IO_ddr_dqs_n),
        .O_tmds_clk_p(O_tmds_clk_p),
        .O_tmds_clk_n(O_tmds_clk_n),
        .O_tmds_data_p(O_tmds_data_p),
        .O_tmds_data_n(O_tmds_data_n),
        .led(led)
    );
endmodule
